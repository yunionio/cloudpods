func TestParseContainerAscendNpuMetrics(t *testing.T) {
	got := parseContainerAscendNpuMetrics(strings.NewReader(npuSmiOutput))

	want := []AscendNpuProcessMetrics{
		{Pid: "1011595", PciAddr: "0000:C1:00.0", MemUtil: 2163.0 / 65536 * 100, Mem: 2163, Idx: 0},
		{Pid: "1011606", PciAddr: "0000:C1:00.0", MemUtil: 2163.0 / 65536 * 100, Mem: 2163, Idx: 0},
		{Pid: "1013240", PciAddr: "0000:81:00.0", MemUtil: 1139.0 / 65536 * 100, Mem: 1139, Idx: 2},
	}

	if len(got) != len(want) {
		t.Fatalf("进程数量不符: got %d, want %d\n got=%+v", len(got), len(want), got)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("第 %d 个进程不符:\n got=%+v\nwant=%+v", i, got[i], want[i])
		}
	}
}

func TestParseContainerAscendNpuMetricsMemTotalFromHbm(t *testing.T) {
	in := `
+---------------------------+---------------+----------------------------------------------------------------------+
| NPU   Name                | Health        | Power(W)             Temp(C)                 Hugepages-Usage(page)   |
| Chip                      | Bus-Id        | AICore(%)            Memory-Usage(MB)        HBM-Usage(MB)           |
+===========================+===============+======================================================================+
| 2     910B2               | OK            | 91.1                 39                      0    / 0                |
| 0                         | 0000:81:00.0  | 0                    0    / 0                3411 / 65536            |
+===========================+===============+======================================================================+
| NPU     Chip              | Process id    | Process name       | Process memory(MB)    | Process id in container |
+===========================+===============+======================================================================+
| 2       0                 | 1013240       | python3            | 32768                  | NA                      |
+===========================+===============+======================================================================+
`
	got := parseContainerAscendNpuMetrics(strings.NewReader(in))
	if len(got) != 1 {
		t.Fatalf("got %d processes, want 1: %+v", len(got), got)
	}
	if got[0].MemUtil != 50 {
		t.Errorf("MemUtil = %v, want 50（应按 HBM 总量 65536 计算）", got[0].MemUtil)
	}
	if got[0].PciAddr != "0000:81:00.0" || got[0].Idx != 2 || got[0].Mem != 32768 {
		t.Errorf("got=%+v, want{Idx:2 PciAddr:0000:81:00.0 Mem:32768}", got[0])
	}
}

func TestParseContainerAscendNpuMetricsEmpty(t *testing.T) {
	in := `
+---------------------------+---------------+----------------------------------------------------------------------+
| NPU     Chip              | Process id    | Process name       | Process memory(MB)    | Process id in container |
+===========================+===============+======================================================================+
| No running processes found in NPU 0                                                                              |
+===========================+===============+======================================================================+
| No running processes found in NPU 1                                                                              |
+===========================+===============+======================================================================+
`
	for name, s := range map[string]string{"empty": "", "noProc": in} {
		if got := parseContainerAscendNpuMetrics(strings.NewReader(s)); len(got) != 0 {
			t.Errorf("%s: want 0 processes, got %+v", name, got)
		}
	}
}
